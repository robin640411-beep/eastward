// Read-only alpha audit; generated baselines avoid pixel scans on mobile devices.
import {readFile,writeFile} from 'node:fs/promises';
import {createRequire} from 'node:module';
import {resolve,dirname} from 'node:path';
import {fileURLToPath} from 'node:url';
import {homedir} from 'node:os';
const root=resolve(dirname(fileURLToPath(import.meta.url)),'..'),require=createRequire(import.meta.url);
let sharp;try{sharp=require('sharp');}catch{sharp=require(resolve(homedir(),'.cache/codex-runtimes/codex-primary-runtime/dependencies/node/node_modules/sharp'));}
const manifest=JSON.parse(await readFile(resolve(root,'dist/assets/manifest.json'),'utf8'));
const entries=[...Object.values(manifest.facilities),{image:manifest.occupation.pylon}];
for(const asset of [...Object.values(manifest.vehicles),...Object.values(manifest.starters||{})])entries.push(asset,...Object.values(asset.variants||{}));
for(const image of Object.values(manifest.characters))entries.push({image});
const metrics={};
for(const asset of entries){
 const key=asset.image+(asset.rect?'#'+asset.rect.join(','):''),old=metrics[key];if(old)continue;
 let pipeline=sharp(resolve(root,'dist/assets',asset.image));
 if(asset.rect){const [left,top,width,height]=asset.rect;pipeline=pipeline.extract({left,top,width,height});}
 const {data,info}=await pipeline.ensureAlpha().raw().toBuffer({resolveWithObject:true});
 let bottom=0,left=info.width,right=0;
 for(let y=0;y<info.height;y++)for(let x=0;x<info.width;x++)if(data[(y*info.width+x)*info.channels+3]>=96){bottom=Math.max(bottom,y+1);left=Math.min(left,x);right=Math.max(right,x+1);}
 if(!bottom)throw Error('No visible ground silhouette: '+key);
 metrics[key]=[info.width,info.height,bottom,left,right];
}
await writeFile(resolve(root,'dist/scenery-ground-data.js'),'// Generated by tools/measure_scenery_ground.mjs. [width, height, visible bottom, left, right]\nexport const SCENERY_GROUND_DATA='+JSON.stringify(metrics,null,1)+';\n');
console.log(JSON.stringify({measured:Object.keys(metrics).length,imagesChanged:0}));
